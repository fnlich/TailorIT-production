import { readFileSync } from 'node:fs';
import {
  GENERAL_FAMILY_ID,
  TECHNICAL_FAMILY_ID,
  asRoleFamilyId,
  type RoleFamilyId,
  type VocabularyEntry,
} from '@tailorit/shared';
import { staticDir } from './paths';

// The skill library (static/skills/skills.json, v2 since v3.3): one file for matching, resume reading, the editor's
// skill picker and tailoring. It began as free_tailor v4.2's tech list (and was tidied since: one main skill per family
// of spellings), took in tailor_builder0's tailoring library (the old tailor-skills.json, its data kept verbatim in each
// entry's `tailor`), and holds the skills of every other field of work. Read once per process.
//
// An entry: a main skill with a priority (1 to 5), the editor's heading (`category`), the rest of its family of
// spellings (`aliases`), the role families it serves (`families`, home family first; absent: every family) and, when
// tailoring lists it, its `tailor` data. An alias is another spelling, a version, a module or a companion of its main
// skill ("Kafka" of "Apache Kafka", "Redux" of "React"): the same keyword (packages/shared/src/match/library-synonyms.ts,
// generated by `npm run skills:synonyms`), filed under its main skill's heading, and the picker offers the main skill
// only (finding it by its aliases too).
//
// Families: the general family reads every entry; any other family reads the entries that name it. A spelling of three
// characters or fewer ("EHR", "IEP") of an entry that does not serve the technical family is that entry's families'
// only: it is never a global synonym ("AR" is accounts receivable to a bookkeeper and augmented reality to an engineer),
// so job keywords pass it to the extractor through the family's vocabulary (`skillsForFamily`).

/** An entry's tailoring data: tailor_builder0's for the technical library, the field's for the others. */
export interface TailorData {
  /** The name tailoring uses when it differs from the entry's ("GCP" of "Google Cloud Platform"). */
  readonly name?: string;
  /** The heading tailoring files it under ("Cloud"); with `priority`, it makes the entry a tailoring skill. */
  readonly heading?: string;
  readonly priority?: number;
  /** Tailoring's alias group, verbatim; absent: the entry's own aliases. */
  readonly aliases?: readonly string[];
  /** The tailoring skill whose alias group holds this entry (an AWS service under "AWS"): a note, not a rule. */
  readonly under?: string;
  /** Breaks a tie of heading and priority in the tailoring list (tailor_builder0's file order); lower first. */
  readonly rank?: number;
  /**
   * v33 FIX-1: the families the block serves when it is not every family the entry serves: a technical library skill
   * that other fields tailor too ("Regression Testing" for QA, "Risk Management" for projects) leaves technical out,
   * so the technical family's tailoring stays tailor_builder0's.
   */
  readonly families?: readonly RoleFamilyId[];
}

export interface HardSkill {
  skill: string;
  priority: number | null;
  category: string;
  /** Other spellings of the skill, as the file writes them. */
  aliases: readonly string[];
  /** The role families it serves, home family first; null: every family. */
  families: readonly RoleFamilyId[] | null;
  tailor: TailorData | null;
}

/** One spelling of a hard skill: the entry's own name, or one of its aliases under the entry's priority and category. */
export interface HardSpelling {
  skill: string;
  priority: number | null;
  category: string;
}

/** Headings that may share one line of a tailored resume's grouped skills. */
export interface TailorGroup {
  name: string;
  categories: readonly string[];
}

export interface SkillLibrary {
  /** One entry per skill, in the file's order (category, priority, name). */
  hard: readonly HardSkill[];
  soft: readonly string[];
  /** Hard skill names only (an alias is the same keyword as its entry), for keyword extraction. */
  vocabulary: readonly string[];
  /** Every spelling: each entry's name, then its aliases. */
  spellings: readonly HardSpelling[];
  /** Lower-cased spelling (an entry's name or an alias) -> its record (the library's own spelling and category). */
  byKey: ReadonlyMap<string, HardSpelling>;
  /** Lower-cased spelling -> its entry. */
  entryByKey: ReadonlyMap<string, HardSkill>;
  /** Tailoring: the heading groups (every family's; each family uses the headings its skills have). */
  tailorGroups: readonly TailorGroup[];
  /** Tailoring's soft skills: `technical` (tailor_builder0's), `shared` (every other field's), and each field's own. */
  tailorSoft: Readonly<Record<string, readonly string[]>>;
}

/** The shortest spelling that may be a global synonym of an entry that does not serve the technical family. */
const GLOBAL_SPELLING_MIN = 4;

const strings = (value: unknown): string[] =>
  Array.isArray(value) ? value.filter((item): item is string => typeof item === 'string' && item.trim() !== '').map((item) => item.trim()) : [];

function familiesOf(value: unknown): RoleFamilyId[] | null {
  if (!Array.isArray(value)) return null;
  const ids = value.map(asRoleFamilyId).filter((id): id is RoleFamilyId => id !== null);
  return ids.length > 0 ? [...new Set(ids)] : null;
}

function tailorOf(value: unknown): TailorData | null {
  if (!value || typeof value !== 'object') return null;
  const t = value as Record<string, unknown>;
  const data: { -readonly [K in keyof TailorData]: TailorData[K] } = {};
  if (typeof t.name === 'string' && t.name.trim()) data.name = t.name.trim();
  if (typeof t.heading === 'string' && t.heading.trim()) data.heading = t.heading.trim();
  if (typeof t.priority === 'number') data.priority = t.priority;
  // Verbatim: tailor_builder0's alias lists are kept as written (their order is the alias group's).
  if (Array.isArray(t.aliases)) data.aliases = t.aliases.filter((alias): alias is string => typeof alias === 'string');
  if (typeof t.under === 'string' && t.under.trim()) data.under = t.under.trim();
  if (typeof t.rank === 'number') data.rank = t.rank;
  const families = familiesOf(t.families);
  if (families) data.families = families;
  return Object.keys(data).length > 0 ? data : null;
}

/** Parses the file's content (exported for the tests). Throws a readable error for a malformed library. */
export function parseSkillLibrary(raw: unknown, where = 'the skill library'): SkillLibrary {
  const data = (raw ?? {}) as { hard?: unknown; soft?: unknown; tailorGroups?: unknown; tailorSoft?: unknown };
  if (!Array.isArray(data.hard) || !Array.isArray(data.soft)) {
    throw new Error(`The skill library at ${where} must have "hard" and "soft" arrays.`);
  }
  const hard: HardSkill[] = [];
  for (const entry of data.hard) {
    const e = (entry ?? {}) as { skill?: unknown; priority?: unknown; category?: unknown; aliases?: unknown; families?: unknown; tailor?: unknown };
    if (typeof e.skill !== 'string' || !e.skill.trim()) continue;
    const skill = e.skill.trim();
    hard.push({
      skill,
      priority: typeof e.priority === 'number' ? e.priority : null,
      category: typeof e.category === 'string' ? e.category : '',
      aliases: strings(e.aliases).filter((alias) => alias.toLowerCase() !== skill.toLowerCase()),
      families: familiesOf(e.families),
      tailor: tailorOf(e.tailor),
    });
  }
  const soft = strings(data.soft);
  const spellings: HardSpelling[] = [];
  for (const { skill, priority, category, aliases } of hard) {
    spellings.push({ skill, priority, category });
    for (const alias of aliases) spellings.push({ skill: alias, priority, category });
  }
  const byKey = new Map<string, HardSpelling>();
  for (const spelling of spellings) if (!byKey.has(spelling.skill.toLowerCase())) byKey.set(spelling.skill.toLowerCase(), spelling);
  const entryByKey = new Map<string, HardSkill>();
  for (const entry of hard) {
    for (const spelling of [entry.skill, ...entry.aliases]) if (!entryByKey.has(spelling.toLowerCase())) entryByKey.set(spelling.toLowerCase(), entry);
  }
  const tailorGroups: TailorGroup[] = [];
  for (const group of Array.isArray(data.tailorGroups) ? data.tailorGroups : []) {
    const g = (group ?? {}) as { name?: unknown; categories?: unknown };
    if (typeof g.name === 'string' && g.name.trim()) tailorGroups.push({ name: g.name.trim(), categories: strings(g.categories) });
  }
  const tailorSoft: Record<string, readonly string[]> = {};
  if (data.tailorSoft && typeof data.tailorSoft === 'object') {
    for (const [name, list] of Object.entries(data.tailorSoft as Record<string, unknown>)) {
      tailorSoft[name] = Array.isArray(list) ? list.filter((item): item is string => typeof item === 'string') : [];
    }
  }
  return { hard, soft, vocabulary: hard.map((s) => s.skill), spellings, byKey, entryByKey, tailorGroups, tailorSoft };
}

let cached: SkillLibrary | null = null;

/** The skill library, parsed once. Throws a readable error if the data file is missing or malformed. */
export function getSkillLibrary(): SkillLibrary {
  if (cached) return cached;
  const file = staticDir('skills', 'skills.json');
  let raw: unknown;
  try {
    raw = JSON.parse(readFileSync(file, 'utf8'));
  } catch (error) {
    throw new Error(`Could not read the skill library at ${file}: ${(error as Error).message}`);
  }
  cached = parseSkillLibrary(raw, file);
  return cached;
}

// ------------------------------------------------------------------------------------------------- families

/** Whether an entry serves a family: general reads every entry, an entry without families serves every family. */
export function servesFamily(entry: Pick<HardSkill, 'families'>, family: RoleFamilyId): boolean {
  return family === GENERAL_FAMILY_ID || entry.families === null || entry.families.includes(family);
}

/** v33 FIX-1: whether an entry's tailoring block serves a family it serves (its own `families`, when it names them). */
export function tailorServes(tailor: Pick<TailorData, 'families'>, family: RoleFamilyId): boolean {
  return family === GENERAL_FAMILY_ID || !tailor.families || tailor.families.includes(family);
}

/**
 * Whether a spelling of an entry is its families' only, never a global synonym: three characters or fewer, of an entry
 * that names its families and not the technical one (the technical library's acronyms, "AWS", "SQL", stay global, as
 * they were in v3.2).
 */
export function isFamilyOnlySpelling(entry: Pick<HardSkill, 'families'>, spelling: string): boolean {
  return spelling.trim().length < GLOBAL_SPELLING_MIN && entry.families !== null && !entry.families.includes(TECHNICAL_FAMILY_ID);
}

/** One family's part of the library. */
export interface FamilySkills {
  family: RoleFamilyId;
  /** The entries it reads: its home entries first (file order), then the others that serve it (file order). */
  hard: readonly HardSkill[];
  /**
   * The keyword extractor's vocabulary (the same array every call, so its scanner is built once): each entry's name, with
   * its family-only short spellings as aliases when the family is one of its own.
   */
  vocabulary: readonly VocabularyEntry[];
}

const familySkills = new WeakMap<SkillLibrary, Map<RoleFamilyId, FamilySkills>>();

/** The skills one role family reads (see `servesFamily`), built once per family. */
export function skillsForFamily(family: RoleFamilyId, library: SkillLibrary = getSkillLibrary()): FamilySkills {
  let byFamily = familySkills.get(library);
  if (!byFamily) {
    byFamily = new Map();
    familySkills.set(library, byFamily);
  }
  const known = byFamily.get(family);
  if (known) return known;
  const serving = library.hard.filter((entry) => servesFamily(entry, family));
  const home = serving.filter((entry) => entry.families?.[0] === family);
  const hard = [...home, ...serving.filter((entry) => entry.families?.[0] !== family)];
  const vocabulary: VocabularyEntry[] = serving.map((entry) => {
    const own = entry.families?.includes(family) ? entry.aliases.filter((alias) => isFamilyOnlySpelling(entry, alias)) : [];
    return own.length > 0 ? { term: entry.skill, aliases: own } : entry.skill;
  });
  const skills: FamilySkills = { family, hard, vocabulary };
  byFamily.set(family, skills);
  return skills;
}

// ------------------------------------------------------------------------------------------------ tailoring

/** One tailoring skill as tailor_builder0's library wrote it: { skill, priority, category (its heading), aliases }. */
export interface TailorLibraryEntry {
  skill: string;
  priority: number;
  category: string;
  aliases: string[];
}

/** A family's tailoring library, in the shape tailor_builder0's file had (`parseSkillsLibrary` reads it). */
export interface TailorLibrary {
  groups: Array<{ name: string; categories: string[] }>;
  hard: TailorLibraryEntry[];
  soft: string[];
}

/**
 * The tailoring library one family reads: the skills with a tailoring heading that serve it, by heading (the groups'
 * order), priority and `rank`, then file order; the groups trimmed to the headings those skills have; and its soft
 * skills (the technical family's own list; any other: the shared list, then its own; general: the shared list and the
 * technical one). For the technical family this is tailor_builder0's library as v3.2 shipped it (a test compares the
 * two).
 */
export function tailorLibraryFor(family: RoleFamilyId, library: SkillLibrary = getSkillLibrary()): TailorLibrary {
  const heads = library.hard
    .map((entry, index) => ({ entry, index, tailor: entry.tailor! }))
    .filter(({ entry }) => entry.tailor?.heading && servesFamily(entry, family) && tailorServes(entry.tailor, family));
  const used = new Set(heads.map(({ tailor }) => tailor.heading!));
  const groups = library.tailorGroups
    .map((group) => ({ name: group.name, categories: group.categories.filter((category) => used.has(category)) }))
    .filter((group) => group.categories.length > 0);
  const headingOrder = groups.flatMap((group) => group.categories);
  const headingRank = (heading: string) => {
    const at = headingOrder.indexOf(heading);
    return at < 0 ? headingOrder.length : at;
  };
  const priorityOf = ({ entry, tailor }: (typeof heads)[number]) => tailor.priority ?? entry.priority ?? 5;
  heads.sort(
    (a, b) =>
      headingRank(a.tailor.heading!) - headingRank(b.tailor.heading!) ||
      priorityOf(a) - priorityOf(b) ||
      (a.tailor.rank ?? Number.MAX_SAFE_INTEGER) - (b.tailor.rank ?? Number.MAX_SAFE_INTEGER) ||
      a.index - b.index,
  );
  const hard = heads.map((head) => ({
    skill: head.tailor.name ?? head.entry.skill,
    priority: priorityOf(head),
    category: head.tailor.heading!,
    aliases: [...(head.tailor.aliases ?? head.entry.aliases)],
  }));
  const own = library.tailorSoft;
  const lists =
    family === TECHNICAL_FAMILY_ID ? [own.technical] : family === GENERAL_FAMILY_ID ? [own.shared, own.technical] : [own.shared, own[family]];
  const seen = new Set<string>();
  const soft: string[] = [];
  for (const name of lists.flatMap((list) => list ?? [])) {
    const key = name.trim().toLowerCase();
    if (family !== TECHNICAL_FAMILY_ID && seen.has(key)) continue;
    seen.add(key);
    soft.push(name);
  }
  return { groups: groups.map((group) => ({ name: group.name, categories: [...group.categories] })), hard, soft };
}

-- v3.5 IMPORT (SP v35 PLAN.md H1, H2, H5, H6 "every admin import is a run"): imports of job links with their rows'
-- fields, for admins and for people, and reposts.
--
-- 1. jobs.reposted_at: when an admin's import last reposted the job (H5: a job TailorIT already had, imported again).
--    The board's own dates are kept (posted_at, and the generated posted_sort, are untouched); the search projection's
--    posted_sort and updated_sort take the later of the job's date and this (GREATEST skips NULL), so a job reposted
--    today is under "Past 24 hours" and near the top of "Recently posted". NULL: never reposted.
-- 2. job_imports: one import (an admin's one link, pasted links, file or Google Sheet; a person's file or Google
--    Sheet): who started it, its run (an admin's import is one run on Runs, H6), its counts once its rows are read.
--    A person's import names the profile it saves to (user_id, the owner) and who imported (actor_id; the grant when
--    acting on a shared profile): JOB_IMPORT_ROWS_MAX and the day's rows (FREE_/PAID_JOB_IMPORT_ROWS_PER_DAY) count
--    toward the actor (`counted`, the rows taken from their day).
-- 3. job_import_rows: each row's result (H2's results), its row number, its link and its given fields, kept for the
--    results view and "Download these rows"; a queued row names its link-queue row until it is read.
-- 4. job_link_queue: `details` (the row's given fields: company, title, description, rate, location; validated on the
--    way in by the shared row contract, never trusted on the way out), `user_id` and `grant_id` (a person's import: the
--    profile it saves to, and the grant it was made under), `import_id` (the import that queued it first); one open row
--    per link and profile (a person's import of a link an admin's import has queued is read for that person too). Its
--    `result` keeps v3.1's four states (the old progress view reads them); each import row keeps H2's own result.
-- 5. job_source_runs.import_summary: an admin import's counts written into its run when its rows are read, so Runs
--    shows them without reading the import tables.
-- 6. job_admin_approvals.kind gains `import` (an admin approved a job made from an admin import's row).
--
-- Additive: new nullable columns (no backfill: existing rows read as before, reposted_at and details NULL), two new
-- tables, wider CHECKs, and the queue's open-row index rebuilt with the profile in it (the table holds at most
-- JOB_LINK_QUEUE_KEEP_DAYS of rows).

ALTER TABLE jobs ADD COLUMN reposted_at timestamptz;

CREATE TABLE job_imports(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL CHECK (kind IN ('admin','user')),
  way text NOT NULL CHECK (way IN ('link','paste','file','sheet')),
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 200),
  run_id bigint REFERENCES job_source_runs(id) ON DELETE SET NULL,
  source_id bigint REFERENCES job_sources(id) ON DELETE SET NULL,
  user_id text REFERENCES users(id) ON DELETE CASCADE,
  actor_id text REFERENCES users(id) ON DELETE SET NULL,
  grant_id text REFERENCES profile_grants(id) ON DELETE SET NULL,
  rows integer NOT NULL CHECK (rows >= 0),
  counted integer NOT NULL DEFAULT 0 CHECK (counted >= 0),
  counts jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(counts) = 'object'),
  config jsonb CHECK (config IS NULL OR jsonb_typeof(config) = 'object'),
  created_at timestamptz NOT NULL,
  finished_at timestamptz,
  notified_at timestamptz,
  CHECK ((kind = 'user') = (user_id IS NOT NULL))
);
-- An admin import's run (GET /api/admin/imports/:runId), one import per run.
CREATE UNIQUE INDEX ux_job_imports_run ON job_imports(run_id) WHERE run_id IS NOT NULL;
-- Recent imports (admins), newest first.
CREATE INDEX idx_job_imports_admin ON job_imports(created_at DESC, id DESC) WHERE kind = 'admin';
-- A person's rows of the last 24 hours (the day's limit), and their imports.
CREATE INDEX idx_job_imports_actor ON job_imports(actor_id, created_at DESC) WHERE kind = 'user';
-- The imports still reading (each pass of the link queue finishes the ones whose rows are read).
CREATE INDEX idx_job_imports_open ON job_imports(id) WHERE finished_at IS NULL;

CREATE TABLE job_import_rows(
  import_id bigint NOT NULL REFERENCES job_imports(id) ON DELETE CASCADE,
  row_number integer NOT NULL CHECK (row_number > 0),
  url text CHECK (url IS NULL OR char_length(url) BETWEEN 9 AND 2100),
  url_key text CHECK (url_key IS NULL OR char_length(url_key) BETWEEN 9 AND 2100),
  details jsonb CHECK (details IS NULL OR jsonb_typeof(details) = 'object'),
  result text NOT NULL CHECK (result IN ('queued','working','added','reposted','known','review','added_private',
                                         'needs_details','closed','failed','repeated')),
  reason text CHECK (reason IS NULL OR char_length(reason) BETWEEN 1 AND 40),
  repeats_row integer CHECK (repeats_row IS NULL OR repeats_row > 0),
  job_id bigint REFERENCES jobs(id) ON DELETE SET NULL,
  queue_id bigint REFERENCES job_link_queue(id) ON DELETE SET NULL,
  PRIMARY KEY (import_id, row_number)
);
-- A read link's rows (every import that queued it).
CREATE INDEX idx_job_import_rows_queue ON job_import_rows(queue_id) WHERE queue_id IS NOT NULL;
-- The jobs of one import (Review's From filter: one import).
CREATE INDEX idx_job_import_rows_job ON job_import_rows(job_id) WHERE job_id IS NOT NULL;

ALTER TABLE job_link_queue
  ADD COLUMN details jsonb CHECK (details IS NULL OR jsonb_typeof(details) = 'object'),
  ADD COLUMN user_id text REFERENCES users(id) ON DELETE CASCADE,
  ADD COLUMN grant_id text REFERENCES profile_grants(id) ON DELETE SET NULL,
  ADD COLUMN import_id bigint REFERENCES job_imports(id) ON DELETE SET NULL;
DROP INDEX ux_job_link_queue_open;
CREATE UNIQUE INDEX ux_job_link_queue_open ON job_link_queue(url_key, (COALESCE(for_job_id, 0)), (COALESCE(user_id, '')))
  WHERE state <> 'done';

ALTER TABLE job_source_runs ADD COLUMN import_summary jsonb CHECK (import_summary IS NULL OR jsonb_typeof(import_summary) = 'object');

ALTER TABLE job_admin_approvals DROP CONSTRAINT job_admin_approvals_kind_check;
ALTER TABLE job_admin_approvals ADD CONSTRAINT job_admin_approvals_kind_check CHECK (kind IN ('captured','legacy','import'));

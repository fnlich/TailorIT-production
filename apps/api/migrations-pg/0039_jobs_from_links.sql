-- v3.1 LINK: every job comes from its link (docs/design/v3.1/21-jobs-from-links.md; the build plan's D1-D3).
--
-- 1. job_verifications: a job only its adder sees because TailorIT could not read its posting from its link (D2: a
--    LinkedIn job, a sign-in page, a page with no schema.org JobPosting, robots.txt, a switch off). One row per such
--    job (the adder's own row of `jobs`, owner_user_id): the canonical link, why it could not be read, when it was last
--    tried and how often. The job's verification state on the DTOs and Admin › Review's "Couldn't verify" list read it.
-- 2. job_link_rejections: links an admin rejected from that list ("not a job TailorIT lists"), by link key: a later add
--    of the same link is never published and stays its adder's own.
-- 3. job_link_queue: the links an import (CSV, JSON, a Google Sheet, the free_tailor lake) or an admin's add queued for
--    TailorIT's own read, read by the ingest worker at each host's pace; a done row keeps its result for the progress
--    view (JOB_LINK_QUEUE_KEEP_DAYS). One open row per link key (a link queued twice is read once).
--
-- The stored links' canonical form (jobs.apply_url, applications.posting_url, job_keys' link keys, job_link_aliases)
-- is written by the jobs feature's daily pass `jobs.links-canonical`, once, in batches, not here: the form is computed
-- by the one shared function (packages/shared/src/jobs/canonical.ts), and an SQL copy of it would be a second source.
-- Additive: new tables only.

CREATE TABLE job_verifications(
  job_id bigint PRIMARY KEY REFERENCES jobs(id) ON DELETE CASCADE,
  user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  url text NOT NULL CHECK (char_length(url) BETWEEN 9 AND 2100 AND left(url, 8) = 'https://'),
  url_key text NOT NULL CHECK (char_length(url_key) BETWEEN 9 AND 2100),
  host text NOT NULL CHECK (char_length(host) BETWEEN 1 AND 253),
  origin text NOT NULL CHECK (origin IN ('web','tracker','mcp','admin','import','sheets','ft_lake','extension','extension_page','applied')),
  reason text NOT NULL CHECK (reason IN ('unreadable_host','no_posting','robots','blocked','unavailable','not_set_up','unlisted',
                                         'opted_out','rejected','closed','invalid_link')),
  checked_at timestamptz NOT NULL,
  attempts integer NOT NULL DEFAULT 1 CHECK (attempts >= 0),
  created_at timestamptz NOT NULL
);
CREATE INDEX idx_job_verifications_url ON job_verifications(url_key);
CREATE INDEX idx_job_verifications_user ON job_verifications(user_id);
CREATE INDEX idx_job_verifications_checked ON job_verifications(checked_at DESC, job_id DESC);

CREATE TABLE job_link_rejections(
  url_key text PRIMARY KEY CHECK (char_length(url_key) BETWEEN 9 AND 2100),
  rejected_by text REFERENCES users(id) ON DELETE SET NULL,
  rejected_at timestamptz NOT NULL
);

CREATE TABLE job_link_queue(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url text NOT NULL CHECK (char_length(url) BETWEEN 9 AND 2100 AND left(url, 8) = 'https://'),
  url_key text NOT NULL CHECK (char_length(url_key) BETWEEN 9 AND 2100),
  host text NOT NULL CHECK (char_length(host) BETWEEN 1 AND 253),
  origin text NOT NULL CHECK (origin IN ('admin','import','sheets','ft_lake')),
  batch_id text CHECK (batch_id IS NULL OR char_length(batch_id) BETWEEN 1 AND 64),
  source_id bigint REFERENCES job_sources(id) ON DELETE SET NULL,
  added_by text REFERENCES users(id) ON DELETE SET NULL,
  state text NOT NULL DEFAULT 'queued' CHECK (state IN ('queued','working','done')),
  result text CHECK (result IN ('published','waiting_admin','private_unverified','refused')),
  reason text,
  job_id bigint REFERENCES jobs(id) ON DELETE SET NULL,
  attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  next_at timestamptz NOT NULL,
  lease_until timestamptz,
  created_at timestamptz NOT NULL,
  done_at timestamptz,
  CHECK ((state = 'done') = (done_at IS NOT NULL))
);
-- One open row per link: a link queued again while it waits is read once.
CREATE UNIQUE INDEX ux_job_link_queue_open ON job_link_queue(url_key) WHERE state <> 'done';
-- The worker's next links (oldest due first), and a lease that ran out.
CREATE INDEX idx_job_link_queue_due ON job_link_queue(next_at, id) WHERE state <> 'done';
-- An Admin add's or an import's progress.
CREATE INDEX idx_job_link_queue_batch ON job_link_queue(batch_id, id) WHERE batch_id IS NOT NULL;
-- The daily prune of done rows.
CREATE INDEX idx_job_link_queue_done ON job_link_queue(done_at) WHERE state = 'done';

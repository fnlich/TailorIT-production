-- v3.1 NOTIFY (docs/design/v3.1/24-notifications-usage.md; build plan D8): in-app notifications (the header's bell and
-- the /notifications page; nothing is mailed) and each person's switches for their groups.
--
-- A notification is written where its event happens (features/notifications: notify), in the event's own transaction
-- or after it committed, never in one that may roll back without the event. Its words are rendered from their message
-- constants when it is written (a later edit of a constant changes new notifications, not old ones). It is kept
-- NOTIFICATIONS_KEEP_DAYS (90) from its creation, read or not (the daily step `notifications.retention`).
--
-- dedupe_key: one notification per person and key (a summary of the hour, a day's budget reached, one job's state):
-- the second write of the same key is skipped (ON CONFLICT DO NOTHING). A key frees up when its row is deleted.
-- link: a path inside TailorIT ("/jobs?jobId=12"), never another site (the web follows it with its router).
-- admin_only: written for an admin as an admin (a run failed, Review's new items); the person's list shows it while
-- they are an admin.
--
-- Two new tables, empty: no row of another table changes.
CREATE TABLE notifications(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind ~ '^[a-z][a-z0-9_]{0,39}$'),
  title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 160),
  body text NOT NULL DEFAULT '' CHECK (char_length(body) <= 1000),
  link text CHECK (link IS NULL OR (char_length(link) <= 500 AND link LIKE '/%' AND link NOT LIKE '//%')),
  dedupe_key text CHECK (dedupe_key IS NULL OR char_length(dedupe_key) BETWEEN 1 AND 200),
  admin_only boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL,
  read_at timestamptz
);
-- The person's list, newest first (keyset on id), and its unread filter and count (the header asks every 60 s).
CREATE INDEX idx_notifications_user ON notifications(user_id, id DESC);
CREATE INDEX idx_notifications_unread ON notifications(user_id, id DESC) WHERE read_at IS NULL;
-- One per person and key.
CREATE UNIQUE INDEX ux_notifications_dedupe ON notifications(user_id, dedupe_key) WHERE dedupe_key IS NOT NULL;
-- The retention step deletes by age.
CREATE INDEX idx_notifications_created ON notifications(created_at);

-- A group a person turned off (or on again). No row: the group is on.
CREATE TABLE notification_prefs(
  user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind_group text NOT NULL CHECK (kind_group IN ('applications','jobs','account','extension','admin')),
  enabled boolean NOT NULL,
  updated_at timestamptz NOT NULL,
  PRIMARY KEY (user_id, kind_group)
);

-- v3.0 E1 (docs/design/part2/13-company-enrichment.md §3.2, §7, §11 phase 1; 11-database.md §5.4): the monthly
-- `refdata` build's record. The build (`npm run refdata:build -- --from <folder>`, features/companies/refdata/) is a
-- command of its own, never the API process: it loads the Wikidata, SEC and GLEIF dumps into a schema `refdata_next`
-- (its tables are migrations-pg/refdata/*.sql, run into that schema at each build, not into `public`), swaps it in for
-- `refdata` by ALTER SCHEMA ... RENAME in one transaction (no reader sees half a build), then matches the companies
-- and writes the coverage report here.
--
-- One build runs at a time: the partial unique index lets one `running` row exist. A build that stops without a word
-- (its process killed) leaves its row running; the next build takes over once the row's heartbeat is old
-- (features/companies/refdata/build.ts).
--
-- A new table, nothing else: no row of another table changes. v3.0 starts on an empty database (DECISIONS P5).
CREATE TABLE refdata_builds(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status text NOT NULL CHECK (status IN ('running', 'done', 'failed')),
  -- What a running build does now (load, index, swap, match, report); the last phase a finished one reached.
  phase text NOT NULL CHECK (phase IN ('load', 'index', 'swap', 'match', 'report')),
  started_at timestamptz NOT NULL,
  heartbeat_at timestamptz NOT NULL,
  finished_at timestamptz,
  -- The fingerprint of the refdata schema files the build ran (readers use a schema of their own fingerprint only).
  format text NOT NULL,
  -- The dump files read: [{source, file, bytes, modifiedAt}] (names and sizes, never their contents).
  inputs jsonb NOT NULL DEFAULT '[]',
  -- Rows loaded per table and the matching's counts.
  counts jsonb NOT NULL DEFAULT '{}',
  -- The coverage report after matching (share of companies and of open jobs per field and per source).
  coverage jsonb,
  error text,
  CHECK ((status = 'running') = (finished_at IS NULL))
);
CREATE UNIQUE INDEX idx_refdata_builds_running ON refdata_builds((true)) WHERE status = 'running';
CREATE INDEX idx_refdata_builds_started ON refdata_builds(started_at DESC);

-- v3.0 X1-API (docs/design/part2/14-extension-reports.md §5.1, §6.2, §7): what the baseline's review tables (14 §9)
-- lacked for two of the design's rules.
--
-- 1. job_review_checks: one row per server re-check of a reported posting (recheckPosting). The re-check budget,
--    EXT_RECHECKS_PER_DAY, counts today's reads exactly (job_reviews.checked_at keeps only the newest check, and a review
--    may be checked again after the 6-hour floor), the floor is kept per job (a new review of a job just checked waits
--    too), and the detail sheet's check history reads it. Names no person. Deleted with its review.
-- 2. job_reviews.reopened_at: an approved closed review whose job its source listed again (jobReviews.reopenedBySource,
--    14 §5.1 step 6). The review stays `approved` (its link was closed); the time marks it "Reopened by its source", and
--    the trust rule counts it against its reporters as a rejection (EXT_REPORTER_REJECTS_TO_IGNORE, 14 §7).
--
-- Additive: a new table, a nullable column, two indexes. No seeded table gains a required column.

CREATE TABLE job_review_checks(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  review_id bigint NOT NULL REFERENCES job_reviews(id) ON DELETE CASCADE,
  job_id bigint NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  state text NOT NULL CHECK (state IN ('gone','live','unreadable','not_possible')),
  link_source_id bigint,
  link_source_job_id text,
  source_made_due boolean NOT NULL DEFAULT false,
  checked_at timestamptz NOT NULL,
  day_key date NOT NULL
);
CREATE INDEX idx_job_review_checks_day ON job_review_checks(day_key);
CREATE INDEX idx_job_review_checks_job ON job_review_checks(job_id, checked_at DESC);
CREATE INDEX idx_job_review_checks_review ON job_review_checks(review_id, checked_at DESC);

ALTER TABLE job_reviews ADD COLUMN reopened_at timestamptz;
CREATE INDEX idx_job_reviews_reopened ON job_reviews(reopened_at) WHERE reopened_at IS NOT NULL;

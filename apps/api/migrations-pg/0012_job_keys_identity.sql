-- v3.0 DB-INGEST (PLAN §9; 11-database.md §5.5, §9.2 step 1h; 12-job-sourcing.md §7): job_keys is every shared identity
-- key a job is known by, and the only one. Ingest writes a job's keys in the job's transaction (features/ingest/keys.ts),
-- matches a posting by them before its text (store.ts's matching order: the source's own id, then the keys, then the
-- company's open job of the same title and text, then the fuzzy fingerprint), and the autofill lookup reads them where
-- v2.0 read jobs.link_key.

-- The key compares in byte order: the lookup's ranges (`key >= ? AND key < ?`, '?' sorting just below '@', '/' just
-- below '0') are byte-order ranges, and with the column in COLLATE "C" the primary key (key_kind, key) serves them.
-- text to text: no table rewrite; the primary key's index is rebuilt (an empty install: nothing to rebuild).
ALTER TABLE job_keys ALTER COLUMN key TYPE text COLLATE "C";

-- Every link key a job held becomes its `link` key (the same value: the shared linkKey of its link). A key that names
-- two jobs cannot happen (idx_jobs_link was unique); ON CONFLICT keeps the first if a key is there already.
INSERT INTO job_keys(key_kind, key, job_id)
  SELECT 'link', link_key, id FROM jobs WHERE link_key IS NOT NULL AND char_length(link_key) <= 2048
  ON CONFLICT (key_kind, key) DO NOTHING;

-- The title key (features/ingest/normalize.ts titleKeyOf: NFKC, lower case, punctuation and symbols as spaces, spaces
-- collapsed) is written by ingest with every job. A row an older writer left without one gets the nearest SQL reading
-- of that rule (an empty install has none; the dry run's seed writes the app's own key).
UPDATE jobs
   SET title_key = btrim(regexp_replace(regexp_replace(lower(normalize(title, NFKC)), '[^[:alnum:][:space:]]+', ' ', 'g'),
                                        '[[:space:]]+', ' ', 'g'))
 WHERE title_key IS NULL;
ALTER TABLE jobs ALTER COLUMN title_key SET NOT NULL;

-- The legacy column and its unique index (PG-0's baseline: "legacy: DB-INGEST drops it").
DROP INDEX idx_jobs_link;
ALTER TABLE jobs DROP COLUMN link_key;

-- The fuzzy match's log (12 §7.3: "every fuzzy merge is logged with its score, and an admin can split it"): one row per
-- posting filed under a job by its text fingerprint alone. Never names a person. Kept with its job (a few rows a day).
CREATE TABLE job_fuzzy_matches(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id bigint NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  source_id bigint REFERENCES job_sources(id) ON DELETE SET NULL,
  source_job_id text COLLATE "C" NOT NULL,
  distance smallint NOT NULL CHECK (distance BETWEEN 0 AND 64),   -- bits between the two SimHash fingerprints
  threshold smallint NOT NULL CHECK (threshold BETWEEN 0 AND 64), -- JOB_FUZZY_SIMHASH_BITS when it matched
  matched_at timestamptz NOT NULL
);
CREATE INDEX idx_job_fuzzy_matches_job ON job_fuzzy_matches(job_id);
CREATE INDEX idx_job_fuzzy_matches_at ON job_fuzzy_matches(matched_at);

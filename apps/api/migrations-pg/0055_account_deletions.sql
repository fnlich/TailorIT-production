-- v3.4 ACCTDEL (PLAN G10, account deletion): a person deletes their own account (Settings › Account › Delete my
-- account) or an administrator deletes one (Admin › Users). Everything the account holds goes in one transaction
-- (features/account-deletion/service.ts). Three changes:
--
-- 1. account_deletion_requests: a deletion asked and not finished yet, written in the same transaction that turns the
--    account off. Deleting the account's row removes it (the key cascades), so a row here only outlives a deletion that
--    stopped part way (a failure, a restart): the daily pass (its first run at start too) finishes every one, Admin ›
--    Users shows the account as "Being deleted", and signing in to it says so.
--      user_id: the account (its key: one request per account).
--      requested_at: when; the shares the deletion ended are the account's that ended from this moment.
--      via: 'self' (the person) or 'admin' (an administrator); the first request's, if asked twice.
-- 2. account_deletions: the one line kept once an account is deleted: when, and whether it was the person or an
--    administrator. Nothing that says whose: no id, no hash of one, no address or name, no count of what it held, no key.
--    Its id is how the server's log names the deletion (`[account] deleted an account (#<id>, self)`).
-- 3. Work someone did on a profile another person shared with them stays that owner's when the account that did it is
--    deleted, as when they leave the share: autofill_agent_queue.prepared_by and prepare_jobs.started_by let go (ON
--    DELETE SET NULL, so nullable) instead of deleting the owner's queue rows and Prepares. NULL reads as the owner's
--    own (prepare/store.ts startedByOf, core/accounts/payer.ts); a new row still names its preparer (the 0049 triggers
--    fill an absent one with the owner).
--
-- Additive: two new empty tables; the two keys keep every row (no value changes).

CREATE TABLE account_deletion_requests(
  user_id text PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  requested_at timestamptz NOT NULL,
  via text NOT NULL CHECK (via IN ('self', 'admin'))
);

CREATE TABLE account_deletions(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deleted_at timestamptz NOT NULL,
  via text NOT NULL CHECK (via IN ('self', 'admin'))
);

ALTER TABLE autofill_agent_queue ALTER COLUMN prepared_by DROP NOT NULL;
ALTER TABLE autofill_agent_queue DROP CONSTRAINT autofill_agent_queue_prepared_by_fkey;
ALTER TABLE autofill_agent_queue
  ADD CONSTRAINT autofill_agent_queue_prepared_by_fkey FOREIGN KEY (prepared_by) REFERENCES users(id) ON DELETE SET NULL;

ALTER TABLE prepare_jobs ALTER COLUMN started_by DROP NOT NULL;
ALTER TABLE prepare_jobs DROP CONSTRAINT prepare_jobs_started_by_fkey;
ALTER TABLE prepare_jobs
  ADD CONSTRAINT prepare_jobs_started_by_fkey FOREIGN KEY (started_by) REFERENCES users(id) ON DELETE SET NULL;
